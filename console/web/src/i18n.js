const entries=Object.entries(phrases).sort((a,b)=>b[0].length-a[0].length);
export function tr(text) {
  if (!english || typeof text!=='string' || !/[\u3400-\u9fff]/u.test(text)) return text;
  if (phrases[text]) return phrases[text];
  for (const [zh,en] of entries) text=text.split(zh).join(en);
  return text;
}
export function localize(root) {
  if (!english || !root) return;
  document.documentElement.lang='en';
  document.querySelector('.brand')?.setAttribute('href','/en/');
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()) {
    const node=walker.currentNode;
    if (node.parentElement?.closest('script,style')) continue;
    const text=tr(node.nodeValue);if(text!==node.nodeValue)node.nodeValue=text;
  }
  for (const node of root.querySelectorAll('[aria-label],[title]'))
    for (const attr of ['aria-label','title']) if(node.hasAttribute(attr)) {
      const value=node.getAttribute(attr), translated=tr(value);
      if(value!==translated)node.setAttribute(attr,translated);
    }
}
